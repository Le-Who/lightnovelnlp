"""
Integration tests — pgvector semantic search.

Level: Integration (requires live PostgreSQL + pgvector extension).
Marker: @pytest.mark.postgres

These tests are ALWAYS SKIPPED locally unless --postgres-url is supplied:
    pytest -m postgres --postgres-url=postgresql://user:pass@localhost/testdb

In CI, the GitHub Actions / Northflank pipeline should:
  1. Spin up postgres:15-pgvector as a service container.
  2. Pass --postgres-url=$TEST_PG_URL to pytest.

Coverage:
  EmbeddingService:
    - generate_embedding() → 768-dim L2-normalized vector
    - vector_to_pgvector_literal() → valid pgvector literal
    - find_similar_terms() → HNSW approximate nearest neighbour search
    - find_similar_terms() threshold filtering
    - find_similar_terms() with no embeddings stored → empty result

  DB schema:
    - pgvector extension is available
    - glossary_terms.embedding_vec column stores/retrieves vector(768)

Notes:
  - Gemini API is MOCKED (no real calls). Embeddings are deterministic
    synthetic vectors generated by `_make_unit_vec()`.
  - Tests do NOT depend on a pre-existing database — postgres_db fixture
    creates all tables fresh and drops them on teardown.
"""

import math
import pytest
from sqlalchemy.orm import Session
from sqlalchemy import text


# ── Helpers ────────────────────────────────────────────────────────────────────


def _make_unit_vec(value: float, dim: int = 768) -> list[float]:
    """
    Create a unit vector where all components are equal, pointing in direction
    `value` (sign determines similarity cluster). After L2 normalization the
    result is a valid unit vector.
    """
    component = value / math.sqrt(dim)
    return [component] * dim


def _store_embedding(db: Session, term_id: int, vec: list[float]) -> None:
    """Insert a pgvector embedding directly via raw SQL (bypasses ORM type system)."""
    vec_literal = "[" + ",".join(f"{v:.8f}" for v in vec) + "]"
    db.execute(
        text("UPDATE glossary_terms SET embedding_vec = :vec::vector WHERE id = :tid"),
        {"vec": vec_literal, "tid": term_id},
    )
    db.commit()


# ── pgvector schema tests ──────────────────────────────────────────────────────


@pytest.mark.postgres
class TestPgvectorSchema:
    def test_pgvector_extension_is_available(self, postgres_db: Session):
        # Arrange + Act
        result = postgres_db.execute(
            text("SELECT extname FROM pg_extension WHERE extname = 'vector'")
        ).fetchone()

        # Assert
        assert result is not None, (
            "pgvector extension not found. Run: CREATE EXTENSION vector;"
        )

    def test_embedding_vec_column_exists_on_glossary_terms(self, postgres_db: Session):
        # Arrange + Act
        result = postgres_db.execute(
            text(
                "SELECT column_name, data_type FROM information_schema.columns "
                "WHERE table_name = 'glossary_terms' AND column_name = 'embedding_vec'"
            )
        ).fetchone()

        # Assert
        assert result is not None, (
            "embedding_vec column missing from glossary_terms. "
            "Run migration 015_add_pgvector_embeddings."
        )

    def test_embedding_vec_column_accepts_768_dim_vector(self, postgres_db: Session):
        # Arrange
        from tests.conftest import make_project, make_glossary_term

        project = make_project(postgres_db)
        term = make_glossary_term(postgres_db, project.id, source_term="Dragon")
        vec = _make_unit_vec(1.0)

        # Act — storing a 768-dim vector must not raise
        _store_embedding(postgres_db, term.id, vec)

        # Assert — retrieved via raw SQL round-trips correctly
        result = postgres_db.execute(
            text(
                "SELECT embedding_vec IS NOT NULL FROM glossary_terms WHERE id = :tid"
            ),
            {"tid": term.id},
        ).scalar()
        assert result is True


