# ── find_similar_terms ─────────────────────────────────────────────────────────


@pytest.mark.postgres
class TestFindSimilarTerms:
    def test_returns_exact_match_when_identical_embedding_stored(
        self, postgres_db: Session, mock_gemini
    ):
        # Arrange
        from app.services.embedding_service import EmbeddingService
        from tests.conftest import make_project, make_glossary_term

        project = make_project(postgres_db, name="Embed Project")
        term = make_glossary_term(postgres_db, project.id, source_term="Sword of Light")
        query_vec = _make_unit_vec(1.0)
        _store_embedding(postgres_db, term.id, query_vec)

        svc = EmbeddingService()

        # Act
        results = svc.find_similar_terms(
            postgres_db, query_vec, project_id=project.id, limit=5, threshold=0.99
        )

        # Assert
        assert len(results) == 1
        assert results[0]["source_term"] == "Sword of Light"
        assert results[0]["similarity"] >= 0.99

    def test_returns_empty_when_no_embeddings_stored(self, postgres_db: Session):
        # Arrange
        from app.services.embedding_service import EmbeddingService
        from tests.conftest import make_project, make_glossary_term

        project = make_project(postgres_db, name="Empty Embed Project")
        make_glossary_term(postgres_db, project.id, source_term="Shadow Realm")
        # No embedding stored ↑

        svc = EmbeddingService()
        query_vec = _make_unit_vec(1.0)

        # Act
        results = svc.find_similar_terms(
            postgres_db, query_vec, project_id=project.id, limit=5
        )

        # Assert
        assert results == []

    def test_threshold_filters_out_dissimilar_terms(self, postgres_db: Session):
        # Arrange
        from app.services.embedding_service import EmbeddingService
        from tests.conftest import make_project, make_glossary_term

        project = make_project(postgres_db, name="Threshold Project")
        similar_term = make_glossary_term(postgres_db, project.id, source_term="Hero")
        dissimilar_term = make_glossary_term(
            postgres_db, project.id, source_term="Villain"
        )

        # Hero → same cluster as query (cosine sim ≈ 1.0)
        _store_embedding(postgres_db, similar_term.id, _make_unit_vec(1.0))
        # Villain → opposite direction (cosine sim ≈ 0)
        _store_embedding(postgres_db, dissimilar_term.id, _make_unit_vec(-1.0))

        svc = EmbeddingService()
        query_vec = _make_unit_vec(1.0)

        # Act — high threshold should exclude Villain
        results = svc.find_similar_terms(
            postgres_db, query_vec, project_id=project.id, limit=10, threshold=0.9
        )

        # Assert
        terms_found = {r["source_term"] for r in results}
        assert "Hero" in terms_found
        assert "Villain" not in terms_found

    def test_respects_project_id_isolation(self, postgres_db: Session):
        # Arrange — two projects, each with a term + embedding
        from app.services.embedding_service import EmbeddingService
        from tests.conftest import make_project, make_glossary_term

        project_a = make_project(postgres_db, name="Project A")
        project_b = make_project(postgres_db, name="Project B")

        term_a = make_glossary_term(postgres_db, project_a.id, source_term="Knight")
        term_b = make_glossary_term(postgres_db, project_b.id, source_term="Rogue")

        vec = _make_unit_vec(1.0)
        _store_embedding(postgres_db, term_a.id, vec)
        _store_embedding(postgres_db, term_b.id, vec)

        svc = EmbeddingService()

        # Act — query only project_a
        results = svc.find_similar_terms(
            postgres_db, vec, project_id=project_a.id, limit=10, threshold=0.0
        )

        # Assert — only Knight (from project_a) is returned
        terms_found = {r["source_term"] for r in results}
        assert "Knight" in terms_found
        assert "Rogue" not in terms_found
