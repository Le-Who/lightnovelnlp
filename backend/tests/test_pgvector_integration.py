    def test_l2_normalize_produces_unit_vector(self, postgres_db: Session):
        # Arrange
        from app.services.embedding_service import EmbeddingService

        raw = [3.0, 4.0] + [0.0] * 766  # norm = 5.0

        # Act
        normalized = EmbeddingService._l2_normalize(raw)

        # Assert
        magnitude = math.sqrt(sum(v**2 for v in normalized))
        assert abs(magnitude - 1.0) < 1e-5

